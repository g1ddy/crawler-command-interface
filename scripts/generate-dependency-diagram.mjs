import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const defaultInput = resolve(repositoryRoot, ".maritime/dependency-graph.json");
const defaultOutput = resolve(repositoryRoot, "docs/images/dependency-graph.svg");

const groups = [
  ["app/components", "UI components"],
  ["app/domain/schema", "Domain schemas"],
  ["app/domain/fixtures", "Runtime fixtures"],
  ["app/domain", "Domain runtime"],
  ["app", "ChatGPT adapter"],
  ["src", "Shared app and Pages adapter"],
];

function quote(value) {
  return JSON.stringify(value);
}

function groupFor(path) {
  return groups.find(([prefix]) => path === prefix || path.startsWith(`${prefix}/`))?.[0];
}

function externalName(dependency) {
  if (!dependency.resolved?.startsWith("node_modules/") || typeof dependency.module !== "string") return undefined;
  const parts = dependency.module.split("/");
  return parts[0].startsWith("@") ? parts.slice(0, 2).join("/") : parts[0];
}

export function graphToDot(graph) {
  if (!graph || !Array.isArray(graph.modules)) {
    throw new Error("Expected Maritime dependency graph to contain a modules array");
  }

  const modules = graph.modules
    .filter(({ source }) => typeof source === "string" && groupFor(source))
    .sort((a, b) => a.source.localeCompare(b.source));
  const moduleNames = new Set(modules.map(({ source }) => source));
  const externals = new Set();
  const edges = [];

  for (const maritimeModule of modules) {
    for (const dependency of maritimeModule.dependencies ?? []) {
      let target;
      if (moduleNames.has(dependency.resolved)) {
        target = dependency.resolved;
      } else {
        const name = externalName(dependency);
        if (name) {
          target = `external:${name}`;
          externals.add(name);
        }
      }
      if (target) edges.push([maritimeModule.source, target]);
    }
  }

  const lines = [
    "// Generated from .maritime/dependency-graph.json. Do not edit.",
    "digraph DependencyGraph {",
    "  graph [bgcolor=\"transparent\", rankdir=LR, pad=\"0.2\", nodesep=\"0.18\", ranksep=\"0.65\", fontname=\"Arial\", fontsize=12];",
    "  node [shape=box, style=\"rounded,filled\", fillcolor=\"#f8fafc\", color=\"#64748b\", fontname=\"Arial\", fontsize=9, margin=\"0.08,0.05\"];",
    "  edge [color=\"#94a3b8\", arrowsize=0.55, penwidth=0.8];",
  ];

  for (const [prefix, label] of groups) {
    const members = modules.filter(({ source }) => groupFor(source) === prefix);
    if (members.length === 0) continue;
    lines.push(`  subgraph ${quote(`cluster_${prefix.replaceAll("/", "_")}`)} {`);
    lines.push(`    label=${quote(label)}; color=\"#cbd5e1\"; style=\"rounded\";`);
    for (const { source } of members) {
      lines.push(`    ${quote(source)} [label=${quote(relative(prefix, source) || source)}];`);
    }
    lines.push("  }");
  }

  if (externals.size > 0) {
    lines.push('  subgraph "cluster_external" {');
    lines.push('    label="External packages"; color="#e2e8f0"; style="rounded,dashed";');
    for (const name of [...externals].sort()) {
      lines.push(`    ${quote(`external:${name}`)} [label=${quote(name)}, fillcolor="#f1f5f9", color="#94a3b8"];`);
    }
    lines.push("  }");
  }

  for (const [source, target] of edges.sort(([a, b], [c, d]) => a.localeCompare(c) || b.localeCompare(d))) {
    lines.push(`  ${quote(source)} -> ${quote(target)};`);
  }
  lines.push("}", "");
  return lines.join("\n");
}

export function generateDiagram(input = defaultInput, output = defaultOutput) {
  const graph = JSON.parse(readFileSync(input, "utf8"));
  const dot = graphToDot(graph);
  try {
    execFileSync("dot", ["-Tsvg", "-o", output], { input: dot, stdio: ["pipe", "inherit", "inherit"] });
  } catch (error) {
    if (error.code === "ENOENT") {
      throw new Error("Graphviz 'dot' is required to generate the architecture diagram", { cause: error });
    }
    throw error;
  }

  // Graphviz includes its local version in this comment; remove it so that the
  // tracked artifact reflects graph and layout changes rather than tool metadata.
  const svg = readFileSync(output, "utf8").replace(/<!-- Generated by graphviz version .*?\n/, "<!-- Generated by Graphviz from .maritime/dependency-graph.json. Do not edit.\n");
  writeFileSync(output, svg);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generateDiagram();
  console.log(`Generated ${relative(repositoryRoot, defaultOutput)} from ${relative(repositoryRoot, defaultInput)}`);
}
